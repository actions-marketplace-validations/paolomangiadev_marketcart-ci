// Entitlement service: Payhip license -> credit grant -> reserved paid job -> result -> consume/release.
// Entitlement comes only from server-side license verification (never a redirect/thank-you page).
// Accounting comes from signed webhooks. Credits are never issued from a webhook alone.

import { complete, getGrant, grantPack, reserve, revoke, type Db } from './ledger.ts';
import { licenseHash, signatureValid, type LicenseVerifier, type PayhipWebhook } from './payhip.ts';
import type { CaseResult } from '../engine/types.ts';

export interface ServiceConfig {
  db: Db;
  verifier: LicenseVerifier;
  productLink: string; // our Payhip product key; anything else is "wrong product"
  pepper: string; // server secret for license hashing
  payhipApiKey: string; // only used to check the webhook signature
  testLicenseHashes?: Set<string>; // our own test purchases: excluded from traction
  now?: () => number;
}

export type ApiError = 'invalid_license' | 'wrong_product' | 'license_disabled' | 'revoked' | 'expired' | 'insufficient_credits' | 'unknown_license' | 'verifier_unavailable';

const BILLABLE = new Set(['PASS', 'REGRESSION']);

export function billableCases(results: CaseResult[]): number {
  return results.reduce((n, r) => n + (BILLABLE.has(r.status) ? r.casesConsumed : 0), 0);
}

async function verifyAndGrant(cfg: ServiceConfig, rawKey: string): Promise<{ ok: true; hash: string } | { ok: false; error: ApiError }> {
  const now = (cfg.now ?? Date.now)();
  const licenseKey = rawKey.trim().toUpperCase(); // Payhip autogenerated keys: five upper-case groups of five characters
  let info;
  try {
    info = await cfg.verifier.verify(licenseKey);
  } catch {
    return { ok: false, error: 'verifier_unavailable' };
  }
  if (!info) return { ok: false, error: 'invalid_license' };
  if (info.product_link !== cfg.productLink) return { ok: false, error: 'wrong_product' };
  const hash = licenseHash(cfg.pepper, licenseKey);
  if (!info.enabled) {
    if (await getGrant(cfg.db, hash)) await revoke(cfg.db, hash, 'license disabled at provider', now);
    return { ok: false, error: 'license_disabled' };
  }
  await grantPack(cfg.db, hash, info.product_link, now, cfg.testLicenseHashes?.has(hash) ?? false);
  return { ok: true, hash };
}

export async function activate(cfg: ServiceConfig, licenseKey: string) {
  const v = await verifyAndGrant(cfg, licenseKey);
  if (!v.ok) return v;
  const g = (await getGrant(cfg.db, v.hash))!;
  if (g.revoked_at !== null) return { ok: false as const, error: 'revoked' as ApiError };
  return { ok: true as const, available: g.available, expiresAt: g.expires_at, test: g.is_test === 1 };
}

// Reserve before running. Re-verifies the license with the provider on every paid job (revocation recheck).
export async function startJob(cfg: ServiceConfig, licenseKey: string, jobId: string, cases: number) {
  const v = await verifyAndGrant(cfg, licenseKey);
  if (!v.ok) return v;
  const r = await reserve(cfg.db, jobId, v.hash, cases, (cfg.now ?? Date.now)());
  if (!r.ok) return { ok: false as const, error: r.reason as ApiError };
  return { ok: true as const, job: r.job, replay: r.replay };
}

// Consume only completed PASS / genuine REGRESSION diagnostics; release ERROR / BLOCKED / UNSUPPORTED.
export async function finishJob(cfg: ServiceConfig, jobId: string, results: CaseResult[]) {
  return complete(cfg.db, jobId, billableCases(results), (cfg.now ?? Date.now)(), JSON.stringify(results.map((r) => ({ caseId: r.caseId, status: r.status, reason: r.reason, durationMs: r.durationMs, casesConsumed: r.casesConsumed }))));
}

export async function runPaidJob(cfg: ServiceConfig, licenseKey: string, jobId: string, cases: number, execute: () => Promise<CaseResult[]>) {
  const s = await startJob(cfg, licenseKey, jobId, cases);
  if (!s.ok) return s;
  if (s.replay && s.job.state === 'completed') return { ok: true as const, replay: true, results: JSON.parse(s.job.result_json ?? '[]'), consumed: s.job.consumed, released: s.job.released };
  if (s.replay) return { ok: false as const, error: 'job_in_progress' as const }; // never execute the same job twice
  let results: CaseResult[] = [];
  try {
    results = await execute();
  } catch {
    results = [];
  }
  const done = await finishJob(cfg, jobId, results);
  const g = (await getGrant(cfg.db, s.job.license_hash))!;
  return { ok: true as const, replay: false, results, consumed: done.job.consumed, released: done.job.released, available: g.available };
}

export async function handleWebhook(cfg: ServiceConfig, payload: PayhipWebhook): Promise<{ status: number; note: string }> {
  if (!signatureValid(payload?.signature, cfg.payhipApiKey)) return { status: 401, note: 'bad signature' };
  if (!payload.id || (payload.type !== 'paid' && payload.type !== 'refunded')) return { status: 200, note: 'ignored event type' };
  const ours = (payload.items ?? []).filter((i) => i.product_key === cfg.productLink);
  if (ours.length === 0) return { status: 200, note: 'not our product; nothing stored' }; // shared store: other products are never recorded
  const now = (cfg.now ?? Date.now)();
  const [ev] = await cfg.db.batch([{ sql: `INSERT OR IGNORE INTO webhook_events (event_key, type, transaction_id, received_at) VALUES (?, ?, ?, ?)`, params: [`${payload.type}:${payload.id}`, payload.type, payload.id, now] }]);
  if (ev.changes === 0) return { status: 200, note: 'duplicate event' };
  if (payload.type === 'paid') {
    await cfg.db.batch([
      {
        sql: `INSERT OR IGNORE INTO sales (transaction_id, product_link, currency, gross_minor, processor_fee_minor, payhip_fee_minor, paid_at) VALUES (?, ?, ?, ?, ?, ?, ?)`,
        params: [payload.id, cfg.productLink, payload.currency, payload.price, payload.stripe_fee ?? null, payload.payhip_fee ?? null, (payload.date ?? now / 1000) * 1000],
      },
    ]);
    return { status: 200, note: 'sale recorded' };
  }
  // refunded: accounting reversal + revoke the refunded licenses (Payhip also disables them; the per-job recheck catches it anyway).
  await cfg.db.batch([
    {
      sql: `INSERT INTO sales (transaction_id, product_link, currency, gross_minor, paid_at, refunded_minor, refunded_at) VALUES (?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(transaction_id) DO UPDATE SET refunded_minor = excluded.refunded_minor, refunded_at = excluded.refunded_at`,
      params: [payload.id, cfg.productLink, payload.currency, payload.price, (payload.date_created ?? now / 1000) * 1000, payload.amount_refunded ?? payload.price, (payload.date_refunded ?? now / 1000) * 1000],
    },
  ]);
  for (const item of ours) if (item.license_key) await revoke(cfg.db, licenseHash(cfg.pepper, item.license_key), 'refunded', now);
  return { status: 200, note: 'refund recorded' };
}
