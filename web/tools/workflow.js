// MarketCart CI — GitHub Actions workflow generator core (no network, no secrets: only secret REFERENCES).
// Action contract checked against paolomangiadev/marketcart-ci v0.2.0 action.yml:
//   inputs mode, cases, api-url, license, storefront-password, source; output exit-code.
(function (root) {
  var ACTION = 'paolomangiadev/marketcart-ci@v0.2.0';
  var API_DEFAULT = 'https://marketcart-ci.pages.dev';
  var TRIGGERS = {
    pr: ['  pull_request:', '  workflow_dispatch:'],
    push: ['  push:', '    branches: [main]', '  workflow_dispatch:'],
    nightly: ['  schedule:', "    - cron: '17 3 * * *'", '  workflow_dispatch:'],
  };

  function clean(s) {
    return String(s == null ? '' : s).trim();
  }

  // opts: { mode: 'demo'|'remote', trigger: 'pr'|'push'|'nightly', casesPath, apiUrl, password: boolean, source }
  function build(opts) {
    var o = opts || {};
    var mode = o.mode === 'remote' ? 'remote' : 'demo';
    var trigger = TRIGGERS[o.trigger] ? o.trigger : 'pr';
    var casesPath = clean(o.casesPath) || 'marketcart/cases.json';
    if (!/^[A-Za-z0-9._\/-]+\.json$/.test(casesPath) || casesPath.indexOf('..') >= 0) throw new Error('cases path must be a relative .json path inside the repository');
    var apiUrl = clean(o.apiUrl) || API_DEFAULT;
    if (!/^https:\/\/[A-Za-z0-9.-]+(\/[A-Za-z0-9._\/-]*)?$/.test(apiUrl)) throw new Error('API URL must be an https URL');
    var source = (clean(o.source) || 'github-action').replace(/[^a-z0-9_-]/gi, '').slice(0, 40) || 'github-action';
    var L = [];
    L.push('# Generated by https://marketcart-ci.pages.dev/tools/github-action-generator/');
    L.push(mode === 'demo'
      ? '# Demo mode: seeded synthetic store with planted cart bugs, no account and no secrets. Exit 0 = demo behaved as expected.'
      : '# Hosted mode: checks YOUR store (Dawn family or Horizon 4.4) from ' + casesPath + '. Exit 0 PASS, 1 REGRESSION, 2 inconclusive, 3 license/API error.');
    L.push('name: marketcart-ci');
    L.push('on:');
    Array.prototype.push.apply(L, TRIGGERS[trigger]);
    L.push('permissions:');
    L.push('  contents: read');
    L.push('jobs:');
    if (mode === 'demo') {
      L.push('  cart-parity-demo:');
      L.push('    runs-on: ubuntu-latest');
      L.push('    steps:');
      L.push('      - uses: ' + ACTION);
      L.push('        with:');
      L.push('          mode: demo');
    } else {
      L.push('  cart-parity:');
      if (trigger === 'pr') {
        L.push('    # Pull requests from forks never receive secrets; skip them instead of failing.');
        L.push("    if: github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository");
      }
      L.push('    runs-on: ubuntu-latest');
      L.push('    steps:');
      L.push('      - uses: actions/checkout@v4');
      L.push('      - id: marketcart');
      L.push('        uses: ' + ACTION);
      L.push('        with:');
      L.push('          mode: remote');
      L.push('          cases: ' + casesPath);
      L.push('          api-url: ' + apiUrl);
      L.push('          license: ${{ secrets.MARKETCART_LICENSE }}');
      if (o.password) L.push('          storefront-password: ${{ secrets.MARKETCART_STOREFRONT_PASSWORD }}');
      L.push('          source: ' + source);
      L.push('      - name: Result');
      L.push('        if: always()');
      L.push('        run: echo "MarketCart exit code ${{ steps.marketcart.outputs.exit-code }}"');
    }
    return L.join('\n') + '\n';
  }

  function casesTemplate(opts) {
    var host = clean((opts || {}).host).toLowerCase().replace(/^https?:\/\//, '').replace(/\/.*$/, '') || 'your-store.myshopify.com';
    return JSON.stringify({
      authorizedDomains: [host],
      cases: [
        { id: 'tee-s', market: { country: 'US', currency: 'USD' }, lines: [{ url: 'https://' + host + '/products/tee?variant=123', variantId: 123, quantity: 1 }] },
        { id: 'tee-m-x2', market: { country: 'US', currency: 'USD' }, lines: [{ url: 'https://' + host + '/products/tee?variant=124', variantId: 124, quantity: 2 }], checks: { total: true } },
      ],
    }, null, 2) + '\n';
  }

  var api = { build: build, casesTemplate: casesTemplate, ACTION: ACTION, API_DEFAULT: API_DEFAULT };
  root.MarketCartWorkflow = api;
})(typeof window !== 'undefined' ? window : globalThis);
