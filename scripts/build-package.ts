// Builds the installable CLI artifacts (npm tarball / `npx github:...`): Node refuses to strip TypeScript types inside
// node_modules, so the package ships JavaScript bundles of the UNCHANGED sources next to them.
//   bin/marketcart.js       <- integrations/cli/marketcart.ts (wrapper; keeps the source's shebang)
//   engine/cli.bundle.js    <- engine/cli.ts (+ engine/*, fixtures/storefront/*); playwright-core stays external
//   engine/run.js           launcher: makes the bundle see itself as engine/cli.ts (its own main-module check)
// Usage: node scripts/build-package.ts [OUT_DIR]   (default: the repository root). Writes only the three files above.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = process.argv[2] ?? ROOT;
mkdirSync(join(OUT, 'bin'), { recursive: true });
mkdirSync(join(OUT, 'engine'), { recursive: true });

const common = { bundle: true, platform: 'node', format: 'esm', target: 'node22', external: ['playwright-core'], legalComments: 'none', logLevel: 'warning' } as const;
await build({ ...common, entryPoints: [join(ROOT, 'integrations/cli/marketcart.ts')], outfile: join(OUT, 'bin/marketcart.js'), banner: { js: '// Generated by scripts/build-package.ts from integrations/cli/marketcart.ts. Do not edit.' } }); // source shebang stays on line 1
await build({ ...common, entryPoints: [join(ROOT, 'engine/cli.ts')], outfile: join(OUT, 'engine/cli.bundle.js'), banner: { js: '// Generated by scripts/build-package.ts from engine/cli.ts (engine sources unchanged). Do not edit.' } });
writeFileSync(join(OUT, 'engine/run.js'), `// Runs the bundled engine exactly like \`node engine/cli.ts <command>\` (used when installed as a package).
import { fileURLToPath } from 'node:url';
process.argv[1] = fileURLToPath(new URL('./cli.ts', import.meta.url));
await import('./cli.bundle.js');
`);
console.log(`built ${OUT}`);
